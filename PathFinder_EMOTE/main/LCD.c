void LCD_delay(volatile int time)  //简单软件延时
{
	volatile unsigned int i;	
	while(time--)
	for(i=500;i>0;i--);
}
void configure_LCD_GPIO(void)
{
    ESP_LOGI("example", "Tiky configure LCD special GPIO!");

	/* Set the GPIO as a push/pull output: CS + SCK + SDA */
	gpio_config_t bk_gpio_config = {
        .mode = GPIO_MODE_OUTPUT,
						//  CS           SCK        SDA
        .pin_bit_mask = (1ULL << 1)|(1ULL << 13)|(1ULL << 20)
    };
    ESP_ERROR_CHECK(gpio_config(&bk_gpio_config));

    gpio_set_level(13, HIGH);
    gpio_set_level(20, HIGH);
}

