static void lcd_panel_init(void)
{
	unsigned int i = 0,j=0;

	for (i = 0;; i++) {
		if (lcm_initialization_setting[i].cmd == REGFLAG_END_OF_TABLE)
			break;
		else if (lcm_initialization_setting[i].cmd == REGFLAG_DELAY)
			LCD_delay(lcm_initialization_setting[i].count);
		else {
			//GP_COMMAD_PA(lcm_initialization_setting[i].count+1);
			SPI_WriteComm(lcm_initialization_setting[i].cmd);
			for(j=0;j<lcm_initialization_setting[i].count;j++)
			SPI_WriteData(lcm_initialization_setting[i].para_list[j]);
		}
	}

	
}
void Lcd_Initialize(void)	//LCD初始化函数
{
    configure_LCD_GPIO();

	LCD_SPI_CS(0);
	LCD_delay(20);
	LCD_SPI_CS(1);
	LCD_delay(10);

    /* ── 软件复位 ST7701S ──
     * GPIO46 在 TK021F2699 上是 RGB VSYNC 而非 LCD RST 脚，
     * 无法用硬件复位。改用 SPI 软件复位命令 (0x01) 强制重置面板。
     * 排线重插后 POR 不可靠时，面板可能停在 Display Inversion ON
     * 的异常状态，表现为底片反相效果。软件复位可恢复默认配置。 */
    SPI_WriteComm(0x01);   /* Software Reset */
    LCD_delay(150);        /* ST7701S datasheet: 等待 ≥120ms */
    SPI_WriteComm(0x11);   /* Sleep Out */
    LCD_delay(120);        /* 等待 ≥50ms，留余量 */

 	lcd_panel_init();

    /* 释放 SPI 引脚，交由 RGB 面板驱动接管 */
    gpio_reset_pin(1);   // CS
    gpio_reset_pin(13);  // SCL
    gpio_reset_pin(20);  // SDA
}
